package app.kavach.guard.core

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.MultipartBody
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONObject
import java.io.IOException
import java.util.concurrent.TimeUnit

/** Talks to the Kavach FastAPI server (POST /api/message, GET /api/rules, GET /health). */
object Api {
    private val client = OkHttpClient.Builder()
        .connectTimeout(20, TimeUnit.SECONDS)
        .readTimeout(120, TimeUnit.SECONDS)  // AI + voice take a few seconds; a sleeping free server ~50 s to wake
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()

    private fun base(url: String) = url.trim().trimEnd('/').let { if (it.startsWith("http")) it else "http://$it" }

    suspend fun analyze(server: String, text: String, output: String, replyLanguage: String): JSONObject =
        withContext(Dispatchers.IO) {
            val body = MultipartBody.Builder().setType(MultipartBody.FORM)
                .addFormDataPart("text", text)
                .addFormDataPart("output", output)
                .addFormDataPart("reply_language", replyLanguage)
                .build()
            val req = Request.Builder().url("${base(server)}/api/message").post(body).build()
            client.newCall(req).execute().use { resp ->
                val raw = resp.body?.string().orEmpty()
                val json = runCatching { JSONObject(raw) }.getOrNull()
                    ?: throw IOException("Server returned ${resp.code}: ${raw.take(120)}")
                if (json.has("error")) throw IOException(json.optString("error"))
                json
            }
        }

    /**
     * Voice assistant command: a WAV recording (Gnani Prisma on the server) or a text command, plus this phone's
     * message records. The server answers only from these records and speaks the reply with Gnani Timbre.
     */
    suspend fun voiceCommand(
        server: String, wav: ByteArray?, text: String?, records: String, focusId: String?, replyLanguage: String,
    ): JSONObject = withContext(Dispatchers.IO) {
        val b = MultipartBody.Builder().setType(MultipartBody.FORM)
            .addFormDataPart("records", records)
            .addFormDataPart("now_ms", System.currentTimeMillis().toString())
            .addFormDataPart("reply_language", replyLanguage)
            .addFormDataPart("output", "both")
        if (wav != null) b.addFormDataPart("audio", "command.wav", wav.toRequestBody("audio/wav".toMediaType()))
        if (!text.isNullOrBlank()) b.addFormDataPart("text", text)
        if (!focusId.isNullOrBlank()) b.addFormDataPart("focus_id", focusId)
        val req = Request.Builder().url("${base(server)}/api/voice/command").post(b.build()).build()
        client.newCall(req).execute().use { resp ->
            val raw = resp.body?.string().orEmpty()
            val json = runCatching { JSONObject(raw) }.getOrNull()
                ?: throw IOException("Server returned ${resp.code}: ${raw.take(120)}")
            if (json.has("error")) throw IOException(json.optString("error"))
            json
        }
    }

    private val slowClient = client.newBuilder().readTimeout(300, TimeUnit.SECONDS).writeTimeout(120, TimeUnit.SECONDS).build()

    /** Call recording -> server (Gnani Prisma batch STT with speaker separation) -> verdict JSON. */
    suspend fun analyzeAudio(server: String, audio: ByteArray, filename: String, replyLanguage: String): JSONObject =
        withContext(Dispatchers.IO) {
            val body = MultipartBody.Builder().setType(MultipartBody.FORM)
                .addFormDataPart("audio", filename, audio.toRequestBody("application/octet-stream".toMediaType()))
                .addFormDataPart("output", "text")
                .addFormDataPart("reply_language", replyLanguage)
                .build()
            val req = Request.Builder().url("${base(server)}/api/message").post(body).build()
            slowClient.newCall(req).execute().use { resp ->
                val raw = resp.body?.string().orEmpty()
                val json = runCatching { JSONObject(raw) }.getOrNull()
                    ?: throw IOException("Server returned ${resp.code}: ${raw.take(120)}")
                if (json.has("error")) throw IOException(json.optString("error"))
                json
            }
        }

    /** Spoken warning (WAV bytes) for an alert, generated by Gnani TTS on the server. */
    suspend fun speak(server: String, text: String, language: String): ByteArray = withContext(Dispatchers.IO) {
        val body = MultipartBody.Builder().setType(MultipartBody.FORM)
            .addFormDataPart("text", text)
            .addFormDataPart("language", language.ifBlank { "auto" })
            .build()
        val req = Request.Builder().url("${base(server)}/api/speak").post(body).build()
        client.newCall(req).execute().use { resp ->
            if (!resp.isSuccessful) throw IOException("speak ${resp.code}")
            resp.body?.bytes() ?: throw IOException("empty audio")
        }
    }

    suspend fun health(server: String): Boolean = withContext(Dispatchers.IO) {
        runCatching {
            client.newCall(Request.Builder().url("${base(server)}/health").build()).execute().use { it.isSuccessful }
        }.getOrDefault(false)
    }

    suspend fun rules(server: String): String? = withContext(Dispatchers.IO) {
        runCatching {
            client.newCall(Request.Builder().url("${base(server)}/api/rules").build()).execute().use {
                if (it.isSuccessful) it.body?.string() else null
            }
        }.getOrNull()
    }
}
